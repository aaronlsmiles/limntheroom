def main(argv=None):
    a = build_parser().parse_args(argv)
    if not in_comfy_venv():
        print(f"lines_job: refuse: run with {COMFY_VENV}/bin/python (this is {sys.executable})", file=sys.stderr)
        return 2
    got = sha256_file(NETG)
    if a.cmd == "hash-netg":
        print(got)
        return 0 if got == NETG_SHA256 else 1
    if got != NETG_SHA256:
        print(f"lines_job: netG.pth hash {got} != {NETG_SHA256}", file=sys.stderr)
        return 1
    try:
        # the frozen environment first: nothing from StillDrawn is imported until its files match their pins
        frozen = {"comfy_venv": check_venv(), "metrics_sha256": check_metrics()}
        inkstab = load_inkstab()
        device, overridden = resolve_device(inkstab._device(), a.device)
        job = Job(inkstab, device, overridden, frozen=frozen)
    except RuntimeError as e:
        print(f"lines_job: refuse: {e}", file=sys.stderr)
        return 1
    {"measure": cmd_measure, "paste-control": cmd_paste, "shift-control": cmd_shift, "shift-room": cmd_shift_room,
     "codec-null": cmd_codec_null}[a.cmd](a, job)
    return 0


