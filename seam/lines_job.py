    common = argparse.ArgumentParser(add_help=False)
    common.add_argument("--device", help=f"override the registered device ({DEVICE}); recorded in the output")
    sub = p.add_subparsers(dest="cmd", required=True)
    m = sub.add_parser("measure", parents=[common])
    m.add_argument("--pair", required=True)
    m.add_argument("--render", required=True, help="the render id; `<take>-noop` for the no-op null")
    m.add_argument("--prompts", help="the render's final render-mask prompt file (not for the no-op)")
    m.add_argument("--null")
    m.add_argument("--kappa", type=float)
    m.add_argument("--out", required=True)
    m.add_argument("--seam")
    pc = sub.add_parser("paste-control", parents=[common])
    pc.add_argument("--input", required=True)
    pc.add_argument("--model", required=True, choices=sorted(controls.NULL_HEIGHT))
    pc.add_argument("--out", required=True)
    sc = sub.add_parser("shift-control", parents=[common])
    sc.add_argument("--input", required=True)
