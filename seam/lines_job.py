#!/usr/bin/env python3
"""The P47 lines job: StillDrawn's frozen line maps, then masked drift, seam cells and stays drawn.

Runs ONLY under ~/tools/ComfyUI/.venv/bin/python, read-only: nothing is installed there (P46's
reproduction gate depends on that venv). The public StillDrawn checkout goes first on sys.path
and metrics.inkstab supplies _line_maps, _chamfer and _tol_iou's definitions under its frozen
DEFS ("inkstab 1.0 (2026-08-12)", iou_tolerance_px 2). The extractor weights netG.pth are
hashed at start and must match NETG_SHA256 (recorded in models/MODELS.md). Before inkstab is
imported, the job refuses unless the venv's Python and key packages are the registered ones
(COMFY_PYTHON, COMFY_VERSIONS) and StillDrawn's metrics files match METRICS_SHA256 (pinned by
content: any commit with identical files is accepted, and the commit is recorded).

    ~/tools/ComfyUI/.venv/bin/python seam/lines_job.py measure --pair P.npz [--null N.npz] \
        [--kappa K] --out OUT.json [--seam OUT.bin]
    ... paste-control --input C.npz --model MODEL --out OUT.json
    ... shift-control --input S.npz --kappa K --out OUT.json
    ... shift-room --input S.npz --kappa K --out OUT.json      (call 133; descriptive)
    ... codec-null --input N.npz --height 720|1080 --m M [--noop] --out OUT.json
    ... hash-netg

Inputs are npz files written by the repo venv (seam/pairs.py; the control inputs are listed in
cmd_paste and cmd_shift). Line maps are extracted once per frame. The take's and the codec
null's maps are cached bit-packed in the gitignored cache/lines/, keyed by sha256 over the frames
and the extraction header (netG hash, inkstab DEFS, device, StillDrawn commit), so each take is
extracted once; render maps are never cached.

measure, per analysis frame t (a = render map, b = take map, R = R(t)):
  D(t)    seam.maskrule.frame_rule(a, b, R) on frames that passed the gate, else None;
  D0(t)   the same for the codec-null pair (the take against its own re-encode) under the
          render's R(t); the null's take must be the pair's take;
  cells   seam.cells.classify under κ (when given), 2-bit seam file; κ_codec = P1 of the null
          pair's room-cell IoUs (the fallback κ_keep); the render's own P1 is reported too. Pixels
          the warp did not cover (the pair's `cover`) are out of R(t), and their cells have no
          verdict, for the render and for the null scored under its R(t) (call 126);
  homes   frame_rule in each resting drawing's home mask (and the null's, for comparison);
  stays drawn  line density in the render's creature mask; inkstab._chamfer between the
          moment-aligned creature lines and the scan crop's line map.
"""
